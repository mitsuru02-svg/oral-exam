// rel（関連・重複する設問）を設問文の先頭一致で解決する。
// 参照先の設問文を書き換えると解決できなくなるので、その場合はコンソールに警告を出す。
const JITCHI_REL = (() => {
  const unresolved = [];
  const map = JITCHI_QA_DATA.map(() => []);
  JITCHI_QA_DATA.forEach((q, i) => {
    (q.rel || []).forEach(key => {
      const hits = JITCHI_QA_DATA.map((x, j) => x.q.startsWith(key) ? j : -1).filter(j => j >= 0);
      if (hits.length !== 1) { unresolved.push(key + '（' + hits.length + '件ヒット）'); return; }
      if (hits[0] !== i) map[i].push(hits[0]);
    });
  });
  if (unresolved.length) console.warn('[jitchi_qa_data] rel の参照を解決できません:', unresolved);
  return map;
})();

